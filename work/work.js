
/* =========================================
   WORK レスポンシブ設定

   基準キャンバス：
   1280 × 650px

   1280 × 650 の座標は変更せず、
   キャンバス全体だけを縮小する
========================================= */

const visualArea =
    document.querySelector(".visual-area");


/* =========================================
   基準サイズ
========================================= */

const canvasWidth = 1280;
const canvasHeight = 650;


/* =========================================
   WORK全体をレスポンシブ表示
========================================= */

function resizeWorkCanvas() {

    /* -------------------------------------
       画面に対して何倍で表示できるか計算
    ------------------------------------- */

    const scaleX =
        window.innerWidth / canvasWidth;

    const scaleY =
        window.innerHeight / canvasHeight;


    /* -------------------------------------
       小さい方の倍率を採用

       → 横・縦どちらも画面内に収まる
    ------------------------------------- */

const scale =
    Math.min(scaleX, scaleY) * 0.8;


    /* -------------------------------------
       1280 × 650 の中央を基準に縮小
    ------------------------------------- */

    visualArea.style.transform =
        `translate(-50%, -50%) scale(${scale})`;

    visualArea.style.transformOrigin =
        "center center";

}


/* =========================================
   初回実行
========================================= */

resizeWorkCanvas();


/* =========================================
   ウィンドウサイズ変更時
========================================= */

window.addEventListener(
    "resize",
    resizeWorkCanvas
);

